"""Φ-Automatic Discriminating Experiment.

Construct a finite experiment frontier from frozen executable theory semantics,
then select an executable, identifiable, budget-feasible experiment that maximizes
predictive divergence between a frozen candidate theory and frozen baselines.

The first qualified search class is deterministic finite executable IR produced by
PHI-THEORY-COMPILER/2.1.0.  Candidate experiments are generated by closure of the
joint theory-state product, not by an arbitrary path-depth cutoff.  Predictions are
obtained only by executing frozen theory IR; caller-supplied prediction tables are
not accepted.  If no admissible query has predictive content, the owner returns
OBSERVATIONALLY_NON_DISTINCT rather than promoting a theory.
"""
from __future__ import annotations

from collections import deque
import math
from pathlib import Path
from typing import Any, Mapping, Sequence

from .candidates import CandidateGenerationPipeline, DirectedResearchQuery
from .runtime import LawSpaceRuntime
from .schema import digest_payload
from .theory_compiler import ExecutableTheoryRuntimeOwner, SCHEMA as EXECUTABLE_SCHEMA

KERNEL_OWNER_ID = "PHI-AUTOMATIC-DISCRIMINATING-EXPERIMENT/1.0.0"
FRONTIER_OWNER_ID = "DISCRIMINATING-EXPERIMENT-FRONTIER/1.0.0"
SELECTION_OWNER_ID = "DISCRIMINATING-EXPERIMENT-SELECTION/1.0.0"
ATTESTATION_BRIDGE_OWNER_ID = "DISCRIMINATING-EXPERIMENT-ATTESTATION-BRIDGE/1.0.0"
SCHEMA = "phi-automatic-discriminating-experiment/v1"


def _with_digest(payload: dict[str, Any]) -> dict[str, Any]:
    payload["digest"] = digest_payload(payload)
    return payload


def _compiled_valid(row: Mapping[str, Any]) -> bool:
    if row.get("status") != "THEORY_EXECUTABLE_COMPILED" or row.get("schema") != EXECUTABLE_SCHEMA:
        return False
    expected = digest_payload({k: v for k, v in row.items() if k != "digest"})
    return bool(row.get("digest")) and row.get("digest") == expected


def _delta_js_bits(a: str, b: str) -> float:
    """Jensen-Shannon divergence between deterministic categorical predictions."""
    return 0.0 if str(a) == str(b) else 1.0


class DiscriminatingExperimentFrontierOwner:
    owner_id = FRONTIER_OWNER_ID

    def __init__(self, runtime: LawSpaceRuntime) -> None:
        self.runtime = runtime
        self.executor = ExecutableTheoryRuntimeOwner()

    def contract(self) -> Mapping[str, Any]:
        return {
            "owner_id": self.owner_id,
            "candidate_source": "INTERNAL_PHI_SCAN_PLUS_FROZEN_EXECUTABLE_THEORY_SEMANTICS",
            "prediction_source": "EXECUTABLE_THEORY_RUNTIME_ONLY",
            "caller_prediction_tables_allowed": False,
            "internet_prefreeze": "FORBIDDEN",
            "frontier_scope": "FINITE_JOINT_STATE_PRODUCT_CLOSURE",
            "fixed_sequence_depth_ceiling": None,
            "required_gates": ["EXECUTABLE", "IDENTIFIABLE_AGAINST_ALL_BASELINES", "COST_WITHIN_BUDGET"],
        }

    @staticmethod
    def _ir(compiled: Mapping[str, Any]) -> Mapping[str, Any]:
        return dict(compiled["executable_ir"])

    @staticmethod
    def _common_schema(theories: Sequence[Mapping[str, Any]]) -> tuple[tuple[str, ...], tuple[str, ...]]:
        state_sets = [set(str(x) for x in t["executable_ir"]["state_schema"]["states"]) for t in theories]
        action_sets = [set(str(x) for x in t["executable_ir"]["update"]["actions"]) for t in theories]
        common_states = tuple(sorted(set.intersection(*state_sets))) if state_sets else ()
        common_actions = tuple(sorted(set.intersection(*action_sets))) if action_sets else ()
        return common_states, common_actions

    @staticmethod
    def _step_state(compiled: Mapping[str, Any], state: str, action: str) -> str:
        return str(compiled["executable_ir"]["update"]["table"][action][state])

    @staticmethod
    def _observe(compiled: Mapping[str, Any], state: str) -> str:
        return str(compiled["executable_ir"]["observe"]["table"][state])

    @staticmethod
    def _protocol_cost(actions: Sequence[str]) -> float:
        # Current qualified finite protocol: one initialization/observation unit plus
        # one intervention unit per typed action.  This is explicit protocol cost,
        # not a claim of a universal computational resource law.
        return 1.0 + float(len(actions))

    def freeze_frontier(
        self,
        *,
        question: str,
        candidate_theory: Mapping[str, Any],
        baseline_theories: Sequence[Mapping[str, Any]],
        cost_budget: float,
    ) -> Mapping[str, Any]:
        baselines = tuple(dict(x) for x in baseline_theories)
        theories = (dict(candidate_theory),) + baselines
        if not baselines:
            return _with_digest({"schema": SCHEMA, "owner_id": self.owner_id, "status": "EXPERIMENT_FRONTIER_BLOCKED_NO_BASELINES"})
        if not math.isfinite(float(cost_budget)) or float(cost_budget) <= 0:
            return _with_digest({"schema": SCHEMA, "owner_id": self.owner_id, "status": "EXPERIMENT_FRONTIER_BLOCKED_INVALID_BUDGET"})
        if not all(_compiled_valid(t) for t in theories):
            return _with_digest({"schema": SCHEMA, "owner_id": self.owner_id, "status": "EXPERIMENT_FRONTIER_BLOCKED_UNQUALIFIED_EXECUTABLE"})

        scan = CandidateGenerationPipeline(self.runtime.catalog, self.runtime.bridges).directed_research(DirectedResearchQuery(
            question=str(question),
            required_observables=("experiment_design", "identifiability", "probability_model", "computational_method"),
            seed_owner_ids=("FND-11", "FND-12", "STRUCTURAL-IDENTIFIABILITY-EQUIVALENCE"),
            discovery_mode="BLIND_PRIMITIVE_FIREWALL",
            include_all_connected_owners=False,
        ))
        states, actions = self._common_schema(theories)
        if not states or not actions:
            return _with_digest({
                "schema": SCHEMA, "owner_id": self.owner_id,
                "status": "EXPERIMENT_FRONTIER_BLOCKED_NO_COMMON_TYPED_PROTOCOL",
                "phi_scan_digest": scan.get("digest"),
            })

        # Exhaust the finite joint-state product.  The first path reaching each joint
        # tuple is sufficient because future deterministic predictions depend only on
        # the current joint tuple.  There is no arbitrary max-depth parameter.
        frontier: list[dict[str, Any]] = []
        seen_global: set[tuple[str, ...]] = set()
        for initial in states:
            start = tuple(initial for _ in theories)
            queue: deque[tuple[tuple[str, ...], tuple[str, ...]]] = deque([(start, ())])
            seen_local = {start}
            seen_global.add(start)
            while queue:
                joint, seq = queue.popleft()
                if seq:
                    final_obs = [self._observe(t, s) for t, s in zip(theories, joint)]
                    divergences = [_delta_js_bits(final_obs[0], b) for b in final_obs[1:]]
                    avg_div = sum(divergences) / len(divergences)
                    identifiable = all(x > 0.0 for x in divergences)
                    cost = self._protocol_cost(seq)
                    core = {
                        "initial_state": initial,
                        "actions": list(seq),
                        "candidate_final_observation": final_obs[0],
                        "baseline_final_observations": final_obs[1:],
                        "candidate_vs_baseline_js_bits": divergences,
                        "mean_predictive_divergence_bits": avg_div,
                        "identifiable_against_all_baselines": identifiable,
                        "executable": True,
                        "protocol_cost": cost,
                        "cost_within_budget": cost <= float(cost_budget),
                        "joint_final_states": list(joint),
                    }
                    qid = "Q-" + digest_payload(core)[:16].upper()
                    frontier.append({"experiment_id": qid, **core})
                for action in actions:
                    nxt = tuple(self._step_state(t, s, action) for t, s in zip(theories, joint))
                    if nxt in seen_local:
                        continue
                    seen_local.add(nxt); seen_global.add(nxt)
                    queue.append((nxt, seq + (action,)))

        # Deduplicate experiment semantics across starting states/path aliases.
        unique: dict[str, dict[str, Any]] = {}
        for row in frontier:
            unique.setdefault(str(row["experiment_id"]), row)
        rows = sorted(unique.values(), key=lambda r: (r["protocol_cost"], r["experiment_id"]))
        freeze_core = {
            "question": str(question),
            "candidate_executable_id": candidate_theory.get("executable_id"),
            "candidate_compiled_digest": candidate_theory.get("digest"),
            "baseline_executable_ids": [x.get("executable_id") for x in baselines],
            "baseline_compiled_digests": [x.get("digest") for x in baselines],
            "phi_scan_digest": scan.get("digest"),
            "cost_budget": float(cost_budget),
            "common_states": list(states),
            "common_actions": list(actions),
            "frontier": rows,
            "frontier_generation": "FINITE_JOINT_STATE_PRODUCT_CLOSURE_NO_ARBITRARY_DEPTH_CEILING",
            "internet_used_prefreeze": False,
            "external_world_observations_used_for_selection": False,
        }
        freeze_digest = digest_payload(freeze_core)
        return _with_digest({
            "schema": SCHEMA,
            "owner_id": self.owner_id,
            "status": "DISCRIMINATING_EXPERIMENT_FRONTIER_FROZEN",
            "freeze_digest": freeze_digest,
            "phi_scan": {
                "registered_axis_count": scan.get("registered_axis_count"),
                "all_registered_axes_visited": scan.get("all_registered_axes_visited"),
                "owner_visits": scan.get("owner_visits"),
                "fixed_owner_visit_budget": scan.get("fixed_owner_visit_budget"),
                "fixed_candidate_axis_order_ceiling": scan.get("fixed_candidate_axis_order_ceiling"),
                "knowledge_firewall": scan.get("knowledge_firewall", {}),
            },
            "frozen": freeze_core,
            "claim_boundary": {
                "world_observation_inspected_before_selection": False,
                "internet_used_prefreeze": False,
                "experiment_world_validity_established": False,
            },
        })


class DiscriminatingExperimentSelectionOwner:
    owner_id = SELECTION_OWNER_ID

    def contract(self) -> Mapping[str, Any]:
        return {
            "owner_id": self.owner_id,
            "objective": "MAXIMIZE_MEAN_PREDICTIVE_DIVERGENCE_SUBJECT_TO_EXECUTABLE_IDENTIFIABLE_COST_BUDGET",
            "divergence": "MEAN_JENSEN_SHANNON_BITS_CANDIDATE_VS_BASELINES",
            "tie_break": "LOWER_PROTOCOL_COST_THEN_CONTENT_ADDRESS",
            "zero_divergence_status": "OBSERVATIONALLY_NON_DISTINCT",
        }

    def select(self, freeze_receipt: Mapping[str, Any]) -> Mapping[str, Any]:
        if freeze_receipt.get("status") != "DISCRIMINATING_EXPERIMENT_FRONTIER_FROZEN":
            return _with_digest({"schema": SCHEMA, "owner_id": self.owner_id, "status": "DISCRIMINATING_EXPERIMENT_BLOCKED_NO_FROZEN_FRONTIER", "selected_experiment": None})
        rows = [dict(x) for x in freeze_receipt.get("frozen", {}).get("frontier", ())]
        if not rows:
            return _with_digest({"schema": SCHEMA, "owner_id": self.owner_id, "status": "OBSERVATIONALLY_NON_DISTINCT", "selected_experiment": None, "max_divergence_bits": 0.0})
        executable_budget = [r for r in rows if r.get("executable") is True and r.get("cost_within_budget") is True]
        max_any = max([float(r.get("mean_predictive_divergence_bits", 0.0)) for r in executable_budget] or [0.0])
        if max_any <= 1e-12:
            return _with_digest({
                "schema": SCHEMA, "owner_id": self.owner_id,
                "status": "OBSERVATIONALLY_NON_DISTINCT", "selected_experiment": None,
                "max_divergence_bits": max_any,
                "reason": "NO_EXECUTABLE_BUDGET_FEASIBLE_QUERY_HAS_PREDICTIVE_DIVERGENCE",
                "theory_promotion_allowed": False,
            })
        admissible = [r for r in executable_budget if r.get("identifiable_against_all_baselines") is True]
        if not admissible:
            return _with_digest({
                "schema": SCHEMA, "owner_id": self.owner_id,
                "status": "NO_FULLY_IDENTIFIABLE_EXPERIMENT_WITHIN_BUDGET", "selected_experiment": None,
                "max_divergence_bits": max_any,
                "theory_promotion_allowed": False,
            })
        admissible.sort(key=lambda r: (-float(r["mean_predictive_divergence_bits"]), float(r["protocol_cost"]), str(r["experiment_id"])))
        best = admissible[0]
        payload = {
            "schema": SCHEMA, "owner_id": self.owner_id,
            "status": "DISCRIMINATING_EXPERIMENT_SELECTED",
            "frontier_freeze_digest": freeze_receipt.get("freeze_digest"),
            "selected_experiment": best,
            "ranked_admissible_experiments": admissible,
            "selection_objective": "MAX_DIVERGENCE_THEN_MIN_COST_THEN_CONTENT_ADDRESS",
            "theory_promotion_allowed": False,
            "claim_boundary": {
                "selection_is_world_falsification": False,
                "selected_experiment_result_already_observed": False,
                "world_theory_novelty_established": False,
            },
        }
        return _with_digest(payload)


class DiscriminatingExperimentAttestationBridgeOwner:
    owner_id = ATTESTATION_BRIDGE_OWNER_ID

    def contract(self) -> Mapping[str, Any]:
        return {
            "owner_id": self.owner_id,
            "output": "WORLD_ATTESTATION_COMPATIBLE_MEASUREMENT_PROTOCOL",
            "measurement_execution_role": "EXTERNAL_OR_TYPED_ADAPTER_AFTER_FREEZE",
            "may_relabel_unexecuted_protocol_as_world_evidence": False,
        }

    def prepare_measurement_protocol(self, selection: Mapping[str, Any]) -> Mapping[str, Any]:
        row = selection.get("selected_experiment") if selection.get("status") == "DISCRIMINATING_EXPERIMENT_SELECTED" else None
        if not isinstance(row, Mapping):
            return _with_digest({"schema": SCHEMA, "owner_id": self.owner_id, "status": "ATTESTATION_BRIDGE_BLOCKED_NO_SELECTED_EXPERIMENT"})
        protocol = {
            "measurement_id": "M-" + digest_payload({"experiment_id": row["experiment_id"], "selection": selection.get("digest")})[:16].upper(),
            "observable_id": "FINAL_TYPED_OBSERVATION",
            "experiment_id": row["experiment_id"],
            "initial_state": row["initial_state"],
            "actions": list(row["actions"]),
            "measurement_owner": "PENDING_TYPED_WORLD_ACTION_OR_EXPERIMENT_OWNER",
            "protocol_digest": digest_payload({"initial_state": row["initial_state"], "actions": list(row["actions"])}),
            "required_result_fields": ["data_digest", "uncertainty", "environment_id", "measurement_owner"],
        }
        return _with_digest({
            "schema": SCHEMA, "owner_id": self.owner_id,
            "status": "WORLD_ATTESTATION_PENDING_EXTERNAL_MEASUREMENT",
            "measurement_protocol": protocol,
            "world_attestation_ready": False,
            "claim_boundary": {
                "protocol_is_measurement": False,
                "protocol_is_world_evidence": False,
                "experiment_selected_before_world_result": True,
            },
        })


class AutomaticDiscriminatingExperimentKernel:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root)
        self.runtime = LawSpaceRuntime(self.root)
        self.frontier = DiscriminatingExperimentFrontierOwner(self.runtime)
        self.selection = DiscriminatingExperimentSelectionOwner()
        self.attestation_bridge = DiscriminatingExperimentAttestationBridgeOwner()

    def contract(self) -> Mapping[str, Any]:
        return {
            "owner_id": KERNEL_OWNER_ID,
            "schema": SCHEMA,
            "owners": {
                "frontier": self.frontier.contract(),
                "selection": self.selection.contract(),
                "attestation_bridge": self.attestation_bridge.contract(),
            },
            "pipeline": "INTERNAL_PHI_SCAN->FREEZE_THEORIES->GENERATE_EXECUTABLE_QUERY_CLOSURE->PREDICT_BY_THEORY_RUNTIME->IDENTIFIABILITY_COST_GATE->MAX_DIVERGENCE->ATTESTATION_PROTOCOL",
            "claim_boundary": {
                "internet_is_prefreeze_experiment_selector": False,
                "caller_prediction_table_is_selection_input": False,
                "selected_experiment_is_world_result": False,
                "synthetic_qualification_is_world_theory_falsification": False,
            },
            "roadmap_dependency": {
                "previous": "PHI-RESOURCE-THEORY-DISCOVERY/1.0.0",
                "next": "LONG-HORIZON-BLIND-SCIENTIFIC-CYCLE",
                "closure_target": "DISCRIMINATING_EXPERIMENT->WORLD_ATTESTATION->ONTOLOGY_REVISION",
            },
        }

    def design(
        self,
        *,
        question: str,
        candidate_theory: Mapping[str, Any],
        baseline_theories: Sequence[Mapping[str, Any]],
        cost_budget: float,
    ) -> Mapping[str, Any]:
        freeze = self.frontier.freeze_frontier(
            question=question,
            candidate_theory=candidate_theory,
            baseline_theories=baseline_theories,
            cost_budget=cost_budget,
        )
        selection = self.selection.select(freeze)
        attestation = self.attestation_bridge.prepare_measurement_protocol(selection)
        status = selection.get("status")
        return _with_digest({
            "schema": SCHEMA, "owner_id": KERNEL_OWNER_ID,
            "status": status,
            "frontier": freeze,
            "selection": selection,
            "attestation_bridge": attestation,
            "claim_boundary": {
                "world_theory_falsified": False,
                "world_theory_confirmed": False,
                "world_novelty_established": False,
                "internet_used_prefreeze": False,
            },
        })
